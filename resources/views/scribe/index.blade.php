        <h1 id="introduction">Introduction</h1>
<p>API REST tipo Facebook: publicaciones con imágenes, comentarios, likes por usuario, búsqueda, paginación y autenticación con tokens (Laravel Sanctum).</p>
<aside>
    <strong>Base URL</strong>: <code>http://127.0.0.1:8000</code>
</aside>
<pre><code>Documentación del taller de Arquitectura y Desarrollo Backend (UNAB).

- **v1** (`/api/v1/...`): API completa. Las mismas rutas existen sin versión (`/api/...`) como alias de compatibilidad.
- **v2** (`/api/v2/posts`): lectura de publicaciones con un formato nuevo (API Resources).
- Envía siempre `Accept: application/json`. Las rutas protegidas piden `Authorization: Bearer {TOKEN}`.</code></pre>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {TOKEN}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Obtén el token con <code>POST /api/v1/register</code> o <code>POST /api/v1/login</code> y envíalo en el header <code>Authorization: Bearer {TOKEN}</code>.</p>

        <h1 id="autenticacion">Autenticación</h1>

    <p>Registro, inicio y cierre de sesión con tokens de Laravel Sanctum.</p>

